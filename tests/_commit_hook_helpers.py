"""Shared builders for the commit-hook and repo-bare doctor checks (#2973).

``test_doctor_commit_hook.py``, ``test_doctor_repo_bare.py`` and
``test_cli_dev_queue_status.py`` all need a client pointing at a real
``tmp_path`` repo, a ``.pre-commit-config.yaml`` with a chosen stage layout, and
a hook script shaped like the one ``pre-commit install`` writes. Hooks are
written by hand here; no test invokes ``pre-commit`` itself.

``tests/_doctor_helpers.py::make_client`` is not a fit (it hard-codes
``workspace_path=Path("/tmp/x")``; these checks run real git in the client
path), nor is ``tests/_changelog_repair_helpers.py::make_client`` (fixed name
and a forced ``worktree_base``).

Executable hooks in the default hooks dir are installed with
``tests._codex_review_helpers._install_pre_commit_hook``; this module only adds
what that helper cannot do.
"""

from __future__ import annotations

import shlex
from typing import TYPE_CHECKING

from cw.models import ClientConfig
from tests._codex_review_helpers import _install_pre_commit_hook

if TYPE_CHECKING:
    from pathlib import Path

# A faithful copy of the script ``pre-commit install --hook-type pre-commit``
# (pre-commit 4.5.1) writes, captured from a real run in a scratch repo; only
# the ``INSTALL_PYTHON`` value and the per-install ``ID`` line vary.
_HOOK_TEMPLATE = """\
#!/usr/bin/env bash
# File generated by pre-commit: https://pre-commit.com
# ID: 138fd403232d2ddd5efb44317e38bf03

# start templated
INSTALL_PYTHON={install_python}
ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-commit)
# end templated

HERE="$(cd "$(dirname "$0")" && pwd)"
ARGS+=(--hook-dir "$HERE" -- "$@")

if [ -x "$INSTALL_PYTHON" ]; then
    exec "$INSTALL_PYTHON" -mpre_commit "${{ARGS[@]}}"
elif command -v pre-commit > /dev/null; then
    exec pre-commit "${{ARGS[@]}}"
else
    echo '`pre-commit` not found.  Did you forget to activate your virtualenv?' 1>&2
    exit 1
fi
"""


def make_hook_client(
    repo: Path,
    *,
    name: str = "acme",
    branch: str | None = None,
    worktree_base: Path | None = None,
) -> ClientConfig:
    """A client over *repo*: workspace mode, or worktree mode when *branch* is set.

    *worktree_base* sets an explicit ``ClientConfig.worktree_base`` (#3076).
    """
    if branch is not None:
        return ClientConfig(
            name=name, repo_path=repo, branch=branch, worktree_base=worktree_base
        )
    return ClientConfig(name=name, workspace_path=repo, worktree_base=worktree_base)


def commit_hook_config(
    *, hook_stages: list[str] | None = None, default_stages: list[str] | None = None
) -> str:
    """Build a one-hook config shared by parser and filesystem tests."""
    lines = []
    if default_stages is not None:
        lines.append(f"default_stages: {default_stages!r}")
    lines += [
        "repos:",
        "  - repo: local",
        "    hooks:",
        "      - id: demo",
        "        name: demo",
        "        entry: 'true'",
        "        language: system",
    ]
    if hook_stages is not None:
        lines.append(f"        stages: {hook_stages!r}")
    return "\n".join(lines) + "\n"


def write_commit_hook_config(
    repo: Path,
    *,
    hook_stages: list[str] | None = None,
    default_stages: list[str] | None = None,
    text: str | None = None,
) -> Path:
    """Write ``<repo>/.pre-commit-config.yaml`` with one ``local`` hook.

    *hook_stages* sets the hook's own ``stages``; *default_stages* sets the
    top-level ``default_stages``. *text* replaces the whole file verbatim
    (malformed-YAML cases).
    """
    path = repo / ".pre-commit-config.yaml"
    if text is None:
        text = commit_hook_config(
            hook_stages=hook_stages, default_stages=default_stages
        )
    path.write_text(text, encoding="utf-8")
    return path


def hook_script(install_python: str) -> str:
    """The generated hook text, recording *install_python* the way pre-commit does."""
    return _HOOK_TEMPLATE.format(install_python=shlex.quote(install_python))


def install_templated_hook(repo: Path, install_python: str) -> None:
    """Install the templated hook (executable) in *repo*'s default hooks dir."""
    _install_pre_commit_hook(repo, hook_script(install_python))


def install_hook_in(
    directory: Path, script: str, *, executable: bool = True, name: str = "pre-commit"
) -> Path:
    """Write *script* as ``<directory>/<name>`` (``core.hooksPath`` cases, #3076).

    *name* defaults to ``pre-commit``; the hook-install-python check also needs
    other hook names (``pre-push``) and ``.sample`` files.
    """
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    path.write_text(script, encoding="utf-8")
    path.chmod(0o755 if executable else 0o644)
    return path
